import os, re, urllib.parse
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rd = lambda p: open(os.path.join(root, p), encoding="utf-8").read()
h = rd("index.html")
h = re.sub(r'<link rel="stylesheet" href="(css/[^"]+)">', lambda m: "<style>\n" + rd(m.group(1)) + "\n</style>", h)
h = re.sub(r'<script src="([^"]+)"></script>', lambda m: "<script>\n" + rd(m.group(1)) + "\n</script>", h)
fav = urllib.parse.quote(rd("assets/favicon.svg"), safe="/:=' ,")
h = h.replace('<link rel="icon" href="assets/favicon.svg" type="image/svg+xml">', '<link rel="icon" href="data:image/svg+xml,' + fav + '">')
os.makedirs(os.path.join(root, "dist"), exist_ok=True)
open(os.path.join(root, "dist", "index.html"), "w", encoding="utf-8").write(h)
print("OK: dist/index.html")
